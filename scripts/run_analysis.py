"""Run sql/telco_churn_analysis.sql section by section on a local PostgreSQL
(embedded via `pip install pgserver`), load the CSV, and save every result.

Usage: python scripts/run_analysis.py <pgdata_dir>
Outputs: results/query_results.md, results/explain_before.txt, results/explain_after.txt,
         dashboard/v_churn_dashboard.csv
"""
import csv
import re
import sys
from pathlib import Path

import pgserver
import psycopg2

ROOT = Path(__file__).resolve().parent.parent
SQL_FILE = ROOT / "sql" / "telco_churn_analysis.sql"
CSV_FILE = ROOT / "data" / "WA_Fn-UseC_-Telco-Customer-Churn.csv"
RESULTS = ROOT / "results"
DASH = ROOT / "dashboard"
RESULTS.mkdir(exist_ok=True)
DASH.mkdir(exist_ok=True)

raw = SQL_FILE.read_text(encoding="utf-8")
labels = {}  # statement index -> nearest preceding "-- Qn." / section label
text = re.sub(r"/\*.*?\*/", "", raw, flags=re.S)

statements, current_label, buf = [], "", []
for line in text.splitlines():
    s = line.strip()
    m = re.match(r"--\s*((Q\d+\.|2\.\d|BEFORE|AFTER|Validate|Action list).*)", s)
    if m and not buf:
        current_label = m.group(1)
    code = re.sub(r"\s--.*$", "", line) if not s.startswith("--") else ""
    buf.append(code)
    if code.strip().endswith(";"):
        stmt = "\n".join(buf).strip()
        if stmt:
            statements.append((current_label, stmt))
        buf = []
        current_label = ""

db = pgserver.get_server(sys.argv[1])
conn = psycopg2.connect(db.get_uri().replace("/postgres", "/postgres"))
conn.autocommit = True
cur = conn.cursor()
out = ["# Query results (generated by scripts/run_analysis.py)\n"]
loaded = False


def table(cols, rows):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    return "\n".join(lines)


explain_n = 0
for label, stmt in statements:
    cur.execute(stmt)
    if stmt.upper().startswith("CREATE TABLE TELCO_RAW"):
        with open(CSV_FILE, encoding="utf-8") as f:
            cur.copy_expert("COPY telco_raw FROM STDIN WITH (FORMAT csv, HEADER true)", f)
        cur.execute("SELECT COUNT(*) FROM telco_raw")
        out.append(f"## Data load\n\nRows loaded into telco_raw: **{cur.fetchone()[0]}**\n")
        continue
    if cur.description:
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        if stmt.upper().startswith("EXPLAIN"):
            explain_n += 1
            name = "explain_before" if explain_n == 1 else "explain_after"
            (RESULTS / f"{name}.txt").write_text("\n".join(r[0] for r in rows), encoding="utf-8")
            out.append(f"## {label or name}\n\n```\n" + "\n".join(r[0] for r in rows) + "\n```\n")
        else:
            out.append(f"## {label or stmt.splitlines()[0]}\n\n" + (table(cols, rows) if rows else "_(0 rows)_") + "\n")
    elif label:
        out.append(f"## {label}\n\nOK ({cur.statusmessage})\n")

(RESULTS / "query_results.md").write_text("\n".join(out), encoding="utf-8")

cur.execute("SELECT * FROM v_churn_dashboard ORDER BY customer_id")
cols = [d[0] for d in cur.description]
with open(DASH / "v_churn_dashboard.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(cols)
    w.writerows(cur.fetchall())
print("done:", len(statements), "statements")
conn.close()
